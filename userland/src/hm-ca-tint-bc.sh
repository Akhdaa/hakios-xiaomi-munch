#!/usr/bin/env bash
# Writes hm_ca_tint_bc.h beside this script: the bitcode of two fragment functions of our own, each returning one
# opaque colour into [[color(0)]], for the plug-in's metal_ca_tint diagnostic (spec metal-ca-reachability-pink, task 9,
# run B): hm_ca_tint_green_fs (0, 1, 0, 1) for the draws D2 leaves out, hm_ca_tint_cyan_fs (0, 1, 1, 1) for the draws of
# an uber shader's own program. Hand-written IR, MIT, in the shape of hakios-metal/tools/kernels/tri_flat_fs.ll (only
# the metadata's shape is Apple's convention). Needs llvm-as. Run again after editing the IR below.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
emit() {   # NAME R G B
	cat > "$tmp/$1.ll" <<EOF
source_filename = "$1"
target datalayout = "e-p:64:64:64-i1:8:8-i8:8:8-i16:16:16-i32:32:32-i64:64:64-f32:32:32-f64:64:64-v16:16:16-v24:32:32-v32:32:32-v48:64:64-v64:64:64-v96:128:128-v128:128:128-v192:256:256-v256:256:256-v512:512:512-v1024:1024:1024-n8:16:32"
target triple = "air64-apple-ios16.5.0"
define <4 x float> @$1() local_unnamed_addr {
  ret <4 x float> <float $2, float $3, float $4, float 1.000000e+00>
}
!air.version = !{!0}
!air.language_version = !{!1}
!air.fragment = !{!2}
!0 = !{i32 2, i32 5, i32 0}
!1 = !{!"Metal", i32 3, i32 0, i32 0}
!2 = !{ptr @$1, !3, !5}
!3 = !{!4}
!4 = !{!"air.render_target", i32 0, i32 0, !"air.arg_type_name", !"float4"}
!5 = !{}
EOF
	llvm-as "$tmp/$1.ll" -o "$tmp/$1.bc"
}
emit hm_ca_tint_green_fs 0.000000e+00 1.000000e+00 0.000000e+00
emit hm_ca_tint_cyan_fs 0.000000e+00 1.000000e+00 1.000000e+00
{
	echo "/* Generated by hm-ca-tint-bc.sh (llvm-as $(llvm-as --version | sed -n 's/.*LLVM version \([0-9.]*\).*/\1/p' | head -1)): do not edit."
	echo " * The metal_ca_tint diagnostic's fragment functions (spec metal-ca-reachability-pink, task 9): opaque green for"
	echo " * the draws D2 leaves out, opaque cyan for an uber shader's own program. Hand-written IR, ours, MIT. */"
	echo "#ifndef HM_CA_TINT_BC_H"
	echo "#define HM_CA_TINT_BC_H"
	for n in hm_ca_tint_green_fs hm_ca_tint_cyan_fs; do
		echo
		echo "static const unsigned char ${n}_bc[] = {"
		xxd -i < "$tmp/$n.bc" | sed 's/^ */\t/'
		echo "};"
	done
	echo
	echo "#endif"
} > "$here/hm_ca_tint_bc.h"
echo "wrote $here/hm_ca_tint_bc.h"
